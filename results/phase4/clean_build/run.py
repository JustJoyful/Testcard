"""Clean-machine test (Phase 4 exit criterion): fresh clone, documented steps only, build, run, score one clip.

    /usr/bin/python3 results/phase4/clean_build/run.py <empty-directory> <clip.mp4>
    /usr/bin/python3 results/phase4/clean_build/run.py --report   # regenerate clean_build.md from steps.json

Standard library only, so nothing from this checkout's environments is used. Writes
results/phase4/clean_build/{steps.json,*.log} in this checkout and results/phase4/clean_build.md.
"""
import json
import os
import re
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / 'results/phase4/clean_build'
CAPS = ['--cpus=4', '--memory=4g', '--pids-limit=128', '--read-only', '--tmpfs', '/tmp:rw,nosuid,size=256m']
PORT, IMAGE, NAME = 8002, 'vqa:clean', 'vqa-clean-test'


def constant(name):
    """Read a hash constant from src/serving_bundle.py as text (its imports need the serving environment)."""
    return re.search(rf"^{name} = '([0-9a-f]{{64}})'", (REPO / 'src/serving_bundle.py').read_text(), re.M).group(1)


def shape_checks():
    """Static checks of the committed serving setup."""
    dockerfile = (REPO / 'Dockerfile').read_text()
    app = (REPO / 'serving/app.py').read_text()
    return [('No Compose file (single Dockerfile, one process; no separate frontend service)',
             not any((REPO / n).exists() for n in ('docker-compose.yml', 'docker-compose.yaml', 'compose.yml', 'compose.yaml'))),
            ('FastAPI serves the built dist/ via StaticFiles', 'StaticFiles' in app and 'COPY --from=web /web/dist/' in dockerfile),
            ('No Redis/Celery; in-process job store', 'JobStore' in app and not any(w in (dockerfile + app).lower() for w in ('redis', 'celery'))),
            ('Weights fetched before the image build (script 12 downloads and SHA256-verifies ResNet-50; the image copies the '
             'verified bundle; DINOv2 is not in the deployed image)', 'COPY artifacts/serving/' in dockerfile)]


def finish(steps, record):
    (OUT / 'steps.json').write_text(json.dumps(dict(steps=steps, result=record), indent=2) + '\n')
    lines = ['# Clean-machine build test', '', 'Generated by `results/phase4/clean_build/run.py`.', '']
    if record:
        prediction = (record['status'].get('result') or {}).get('prediction', {})
        lines += [f"Commit `{record['commit']}`, fresh clone in an empty directory, empty uv cache, `docker build --no-cache`.", '',
                  f"- Image size: {record['image_size_bytes'] / 1e9:.2f} GB; build time: {record['build_seconds'] / 60:.1f} min.",
                  f"- Test clip `{record['clip']}`: state `{record['status']['state']}`, score {prediction.get('score')}, "
                  f"timings {prediction.get('timings_seconds')}.",
                  f"- Startup log: `{record['startup_log_line']}`.",
                  '- Startup hashes match the reported checkpoint (results/phase3/deployment.json), weights and preprocessing '
                  f"(Rule 28): **{'yes' if record['hashes_match'] else 'NO'}**.", '']
    lines += ['## Serving shape (Task 5 step 1)', '']
    lines += [f'- {name}: **{"yes" if ok else "NO"}**' for name, ok in shape_checks()] + ['']
    lines += ['## Exact commands', '', '| # | Step | Command | Documented | Exit | Seconds | Note |', '|---|---|---|---|---|---|---|']
    lines += [f"| {i} | {s['step']} | `{s['command']}` | {'yes' if s['documented'] else '**no**'} | {s['exit_code']} | {s['seconds']} | {s['note']} |"
              for i, s in enumerate(steps, 1)]
    lines += ['', '## Steps that needed something undocumented', '']
    lines += [f"- **{s['step']}**: {s['note']}" for s in steps if not s['documented']] or ['- None.']
    (REPO / 'results/phase4/clean_build.md').write_text('\n'.join(lines) + '\n')


def main(work, clip):
    work, clip = Path(work).resolve(), Path(clip).resolve()
    if work.exists() and any(work.iterdir()):
        raise SystemExit('the work directory must be new or empty')
    work.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    clone = work / 'VQA'
    env = {**os.environ, 'UV_CACHE_DIR': str(work / 'uv-cache')}  # empty package cache: nothing reused
    steps = []

    def step(name, command, documented, note='', cwd=clone):
        start = time.perf_counter()
        result = subprocess.run(command, cwd=cwd, env=env, capture_output=True, text=True)
        log = OUT / f'{len(steps) + 1:02d}_{name}.log'
        log.write_text(result.stdout + result.stderr)
        steps.append(dict(step=name, command=' '.join(command), documented=documented, note=note, exit_code=result.returncode,
                          seconds=round(time.perf_counter() - start, 1), log=str(log.relative_to(REPO))))
        print(json.dumps(steps[-1]), flush=True)
        if result.returncode:
            finish(steps, None)
            raise SystemExit(f'step failed: {name}')
        return result

    step('clone', ['git', 'clone', str(REPO), str(clone)], False,
         'No public remote yet, so cloned from the local repository path. The run steps live in docs/, which is not committed.', cwd=work)
    commit = step('commit', ['git', 'rev-parse', 'HEAD'], False, 'records the tested commit').stdout.strip()
    step('lfs_install', ['git', 'lfs', 'install', '--local'], False,
         'Without Git LFS filters configured, `git lfs pull` prints "Skipping object checkout, Git LFS is not installed for this '
         'repository" and leaves every LFS file (including the ridge model) as a pointer. Repo-local install used here.')
    step('lfs_model', ['git', 'lfs', 'pull', '--include=results/phase3/refit/resnet50/ridge/seedNone/model.npz'], True)
    step('lfs_phase3', ['git', 'lfs', 'pull', '--include=results/phase3/**'], False,
         'Script 12 verifies every Phase 3 output, including LFS neural checkpoints (best.pt); the documented pull fetches only '
         'the ridge model.npz, so preparation fails with "LFS pointer requires materialization: best.pt" without this pull.')
    step('venv', ['uv', 'venv', '--python', '3.11.15', '.venv-serving'], False,
         'Documented `uv venv --python .venv/bin/python` needs the research .venv, which a clone does not have; used a uv-managed CPython 3.11.15.')
    step('install', ['uv', 'pip', 'sync', '--python', '.venv-serving/bin/python', '--require-hashes', '--index-url', 'https://pypi.org/simple',
                     '--extra-index-url', 'https://download.pytorch.org/whl/cpu', '--index-strategy', 'unsafe-best-match',
                     'env/serving.lock'], True)
    step('prepare_bundle', ['.venv-serving/bin/python', '-m', 'scripts.12_prepare_serving', '--config', 'configs/serving.yaml',
                            '--output', 'artifacts/serving'], True, 'downloads and SHA256-verifies the ResNet-50 weights')
    step('docker_build', ['docker', 'build', '--no-cache', '-t', IMAGE, '.'], True)
    subprocess.run(['docker', 'rm', '-f', NAME], capture_output=True)
    step('docker_run', ['docker', 'run', '-d', '--name', NAME, *CAPS, '-p', f'127.0.0.1:{PORT}:8000', IMAGE], True,
         f'documented command uses --rm and port 8001; here -d, a name and port {PORT} so the existing demo container keeps running')
    url = f'http://127.0.0.1:{PORT}'
    for _ in range(180):
        try:
            if json.loads(urllib.request.urlopen(url + '/health', timeout=2).read())['status'] == 'ready':
                break
        except OSError:
            time.sleep(1)
    task = json.loads(step('upload', ['curl', '-sS', '-F', f'file=@{clip}', url + '/upload'], True).stdout)['task_id']
    for _ in range(300):
        status = json.loads(urllib.request.urlopen(f'{url}/status/{task}', timeout=10).read())
        if status['state'] in ('done', 'error'):
            break
        time.sleep(1)
    logs = subprocess.run(['docker', 'logs', NAME], capture_output=True, text=True)
    line = next((l for l in (logs.stdout + logs.stderr).splitlines() if 'verified runtime: ' in l), None)
    startup = json.loads(line.split('verified runtime: ', 1)[1]) if line else None
    size = int(subprocess.run(['docker', 'image', 'inspect', IMAGE, '--format', '{{.Size}}'], capture_output=True, text=True).stdout)
    deployment = json.loads((REPO / 'results/phase3/deployment.json').read_text())
    reported = dict(model_sha256=deployment['checkpoint_sha256'], weights_sha256=constant('WEIGHTS_SHA256'),
                    preprocessing_sha256=constant('PREPROCESSING_SHA256'))
    record = dict(commit=commit, work_directory=str(work), clip=clip.name, image_size_bytes=size,
                  build_seconds=next(s['seconds'] for s in steps if s['step'] == 'docker_build'),
                  status=status, startup_log_line=line, startup_verified=startup, reported=reported,
                  model_constant_matches_deployment=constant('MODEL_SHA256') == deployment['checkpoint_sha256'],
                  hashes_match=bool(startup) and all(startup[k] == v for k, v in reported.items()))
    subprocess.run(['docker', 'rm', '-f', NAME], capture_output=True)
    finish(steps, record)
    print(json.dumps(dict(hashes_match=record['hashes_match'], state=status['state'])))


if __name__ == '__main__':
    if sys.argv[1:] == ['--report']:
        saved = json.loads((OUT / 'steps.json').read_text())
        finish(saved['steps'], saved['result'])
    else:
        main(*sys.argv[1:3])
